impl Cmd {
    pub fn is_editor(self) -> bool {
        use Cmd::*;
        matches!(
            self,
            Move(..)
                | Backspace
                | Delete
                | DeleteWordBack
                | DeleteWordForward
                | Newline
                | Tab
                | Indent
                | Unindent
                | SelectAll
                | SelectLine
                | SelectNext
                | SelectAllOccurrences
                | SplitLines
                | AddCursorAbove
                | AddCursorBelow
                | DuplicateLine
                | DeleteLine
                | MoveLineUp
                | MoveLineDown
                | ToggleComment
                | JoinLines
                | InsertLineAfter
                | InsertLineBefore
                | UpperCase
                | LowerCase
                | SortLines
                | GotoBracket
                | GitNextChange
                | GitPrevChange
                | GitRevertChange
                | GitRevertFile
                | Undo
                | Redo
        )
    }

    /// Editor commands that change the text (refused on read-only buffers).
    pub fn modifies(self) -> bool {
        use Cmd::*;
        self.is_editor()
            && !matches!(
                self,
                Move(..)
                    | SelectAll
                    | SelectLine
                    | SelectNext
                    | SelectAllOccurrences
                    | SplitLines
                    | AddCursorAbove
                    | AddCursorBelow
                    | GotoBracket
                    | GitNextChange
                    | GitPrevChange
            )
    }
}

